"""Fetch a small, openly licensed photo for every lookalike bird that isn't in the library.

Reads the lookalikes in app/src/data/birds.json, skips names that are library birds (they
already have photos), and takes the lead image of each one's English Wikipedia article.
Same license rules as fetch_photos.py: CC0, public domain, CC BY and CC BY-SA only.

Writes 400px images to app/assets/lookalikes/<slug>.jpg|.png, credits to
app/src/data/lookalike-photos.json, and the static require() index to
app/src/data/lookalike-files.ts.

Usage: python pipeline/fetch_lookalike_photos.py
"""
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path

import fetch_photos as fp

fp.WIDTH = 400
ROOT = fp.ROOT
OUT_DIR = ROOT / "app/assets/lookalikes"
CREDITS = ROOT / "app/src/data/lookalike-photos.json"
INDEX = ROOT / "app/src/data/lookalike-files.ts"


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower().replace("'", "")).strip("-")


def main() -> int:
    birds = json.loads(fp.BIRDS.read_text(encoding="utf-8"))
    library = {b["commonName"] for b in birds}
    names = sorted({l["name"] for b in birds for l in b.get("lookalikes", [])} - library)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    credits = json.loads(CREDITS.read_text(encoding="utf-8")) if CREDITS.exists() else {}
    missing: list[str] = []

    for name in names:
        key = slug(name)
        if key in credits and any((OUT_DIR / f"{key}{e}").exists() for e in (".jpg", ".png")):
            continue
        try:
            image = fp.lead_image(name)
            info = fp.image_info(image) if image else None
            if not info:
                missing.append(f"{name}: no lead image")
                continue
            meta = info.get("extmetadata", {})
            lic = fp.plain(meta.get("LicenseShortName", {}).get("value", ""))
            if not fp.allowed(lic):
                missing.append(f"{name}: license {lic!r} not allowed ({image})")
                continue
            url = info.get("thumburl") or info["url"]
            path = url.lower().split("?")[0]
            ext = ".png" if path.endswith(".png") else ".jpg"
            if ext == ".jpg" and not path.endswith((".jpg", ".jpeg")):
                missing.append(f"{name}: not a JPEG or PNG ({image})")
                continue
            (OUT_DIR / f"{key}{ext}").write_bytes(fp.fetch(url))
            artist = fp.plain(meta.get("Artist", {}).get("value", ""))
            artist = artist.replace("No machine-readable author provided. ", "").replace(" assumed (based on copyright claims).", "")
            credits[key] = {"name": name, "artist": artist or "Unknown", "license": lic,
                            "source": info.get("descriptionurl", ""), "file": image}
            print(f"ok   {name}  {lic}")
            time.sleep(2)
        except Exception as e:
            missing.append(f"{name}: {e}")

    credits = {k: credits[k] for k in sorted(credits)}
    CREDITS.write_text(json.dumps(credits, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = ["// Generated by pipeline/fetch_lookalike_photos.py. Do not edit by hand.", "/* eslint-disable */",
             "export const LOOKALIKE_FILES: Record<string, number> = {"]
    for key in credits:
        for ext in (".jpg", ".png"):
            if (OUT_DIR / f"{key}{ext}").exists():
                lines.append(f"  '{key}': require('../../assets/lookalikes/{key}{ext}'),")
                break
    lines.append("};")
    INDEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n{len(credits)}/{len(names)} lookalikes have photos")
    for m in missing:
        print("MISSING", m)
    return 0


if __name__ == "__main__":
    sys.exit(main())
